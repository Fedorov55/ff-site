from fpdf import FPDF
import os

root = 'C:/Users/Eblan/Documents/Проект по умолчанию/ff-site/files'
font_path = 'C:/Windows/Fonts/arial.ttf'

def create_pdf(filename, title, subtitle, sections, footer_text):
    pdf = FPDF()
    pdf.add_page()
    pdf.add_font('Arial', '', font_path, uni=True)
    pdf.set_font('Arial', '', 12)
    
    # Title
    pdf.set_text_color(180, 140, 40)  # gold-ish
    pdf.set_font('Arial', '', 22)
    pdf.cell(0, 12, title, ln=True, align='C')
    pdf.ln(2)
    
    # Subtitle
    pdf.set_text_color(80, 80, 80)
    pdf.set_font('Arial', '', 12)
    pdf.cell(0, 8, subtitle, ln=True, align='C')
    pdf.ln(6)
    
    # Line
    pdf.set_draw_color(212, 175, 55)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(8)
    
    # Sections
    for sec_title, items in sections:
        pdf.set_text_color(20, 20, 20)
        pdf.set_font('Arial', '', 14)
        pdf.cell(0, 8, sec_title, ln=True)
        pdf.ln(2)
        pdf.set_font('Arial', '', 11)
        for item in items:
            pdf.set_text_color(60, 60, 60)
            pdf.multi_cell(0, 6, f'• {item}', ln=True)
            pdf.ln(1)
        pdf.ln(4)
    
    # Footer
    pdf.ln(6)
    pdf.set_draw_color(212, 175, 55)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(4)
    pdf.set_text_color(100, 100, 100)
    pdf.set_font('Arial', '', 9)
    pdf.multi_cell(0, 5, footer_text, align='C')
    
    out = os.path.join(root, filename)
    pdf.output(out)
    print(f'Created {filename}')

