for case_path, data in cases_data.items():
    full_path = os.path.join(root, case_path)
    if not os.path.exists(full_path):
        print(f'MISSING: {case_path}')
        continue
    s = open(full_path, encoding='utf-8').read()
    original = s

    # Replace title
    s = re.sub(r'<title>.*?</title>', f'<title>{data["title"]} | F&F</title>', s)
    # Replace h1
    s = re.sub(r'<h1 class="page-intro__title">.*?</h1>', f'<h1 class="page-intro__title">{data["h1"]}</h1>', s)
    # Replace lead
    s = re.sub(r'<p class="page-intro__lead">.*?</p>', f'<p class="page-intro__lead">{data["lead"]}</p>', s)
    # Replace task paragraph (in case-summary-card 01)
    s = re.sub(r'(<span>01 · Задача</span>\s*<h2>С чем пришёл клиент</h2>\s*<p>).*?(</p>)', f'\\g<1>{data["task"]}\\g<2>', s, flags=re.S)
    # Replace work paragraph
    s = re.sub(r'(<span>02 · Работы</span>\s*<h2>Что сделали</h2>\s*<p>).*?(</p>)', f'\\g<1>{data["work"]}\\g<2>', s, flags=re.S)
    # Replace result paragraph
    s = re.sub(r'(<span>03 · Результат</span>\s*<h2>Что изменилось</h2>\s*<p>).*?(</p>)', f'\\g<1>{data["result"]}\\g<2>', s, flags=re.S)

    if s != original:
        open(full_path, 'w', encoding='utf-8').write(s)
        print(f'Updated {case_path}')
    else:
        print(f'No changes {case_path}')

print('Done')
